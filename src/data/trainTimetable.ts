/**
 * Helper to construct hydrated initial train records with estimated arrival and ISO timestamps.
 */
export function getInitialTrainRecords(): TrainRecord[] {
  const now = '2026-10-12T02:30:00.000Z';
  return RAW_TRAIN_TIMETABLE.map((raw) => {
    const estimatedArrivalPune = addMinutesToTimeString(raw.scheduledArrivalPune, raw.delayMinutes);
    return {
      ...raw,
      id: `train-${raw.trainNumber}`,
      estimatedArrivalPune,
      priorityScore: raw.delayMinutes,
      lastUpdated: now,
    };
  });
}
